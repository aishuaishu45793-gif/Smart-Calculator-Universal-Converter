
"""Length conversion functions."""

def km_to_miles(km):
    return km * 0.621371

def miles_to_km(miles):
    return miles / 0.621371

def meters_to_feet(meters):
    return meters * 3.28084

def feet_to_meters(feet):
    return feet / 3.28084

def cm_to_inches(cm):
    return cm * 0.393701

def inches_to_cm(inches):
    return inches / 0.393701
